_BY_TICKER = {row["ticker"]: row for row in TICKER_DIRECTORY}
SECTORS = sorted({row["sector"] for row in TICKER_DIRECTORY if row["sector"] != "ETF"})


def lookup(ticker: str) -> dict[str, str] | None:
    return _BY_TICKER.get(ticker.upper())


def search(query: str, *, limit: int = 8) -> list[dict[str, str]]:
    q = query.strip().upper()
    if not q:
        return []
    starts_with = [r for r in TICKER_DIRECTORY if r["ticker"].upper().startswith(q)]
    contains = [
        r
        for r in TICKER_DIRECTORY
        if r not in starts_with and (q in r["name"].upper() or q in r["ticker"].upper())
    ]
    return (starts_with + contains)[:limit]


def candidates(*, sector: str | None = None, exclude_etfs: bool = True) -> list[dict[str, str]]:
    """The screener's candidate universe: the full directory, optionally
    narrowed by sector. ETFs are excluded by default since most screener
    criteria (P/E, margins, etc.) don't apply to them."""
    rows = TICKER_DIRECTORY
    if exclude_etfs:
        rows = [r for r in rows if r["sector"] != "ETF"]
    if sector:
        rows = [r for r in rows if r["sector"].lower() == sector.lower()]
    return rows
